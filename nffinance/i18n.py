def fmt_eur(cents: int) -> str:
    """1234567 -> '12.345,67 €'（奥地利/德语格式）"""
    neg = cents < 0
    cents = abs(int(cents))
    s = f"{cents // 100:,}".replace(",", ".") + f",{cents % 100:02d}"
    return ("-" if neg else "") + s + " €"
